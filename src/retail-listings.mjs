const CHANNEL_NAMES = Object.freeze({
  kdp: "Amazon Kindle Direct Publishing",
  "kdp-paperback": "Amazon KDP Paperback",
  kobo: "Kobo Writing Life",
  "google-play-books": "Google Play Books Partner Center",
  "apple-books": "Apple Books for Authors",
  "barnes-noble-press": "Barnes & Noble Press",
  leanpub: "Leanpub",
});

// Retail title plus subtitle may run to 200 characters on KDP; seven keywords.
const KDP_KEYWORDS = 7;
const KDP_KEYWORD_LENGTH = 50;

const dollars = (cents) => (cents / 100).toFixed(2);

/** What KDP charges to print one black-ink paperback in the US marketplace, in cents. */
export function kdpPaperbackPrintingCents(pages) {
  if (!Number.isInteger(pages) || pages < 24 || pages > 828) throw new RangeError(`a KDP black-ink paperback has 24 to 828 pages, not ${pages}`);
  return pages < 110 ? 230 : Math.round(100 + 1.2 * pages);
}

function namesMark(text, marks) {
  const lower = String(text ?? "").toLowerCase();
  return marks.filter((mark) => new RegExp(`(^|[^a-z0-9])${mark.toLowerCase().replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")}([^a-z0-9]|$)`, "u").test(lower));
}

/** The description a retailer shows, with the independence statement a book that names others' marks carries. */
export function retailDescription(offering) {
  const marks = offering.book?.marks ?? [];
  const kind = offering.book?.profile === "study-guide" ? "study companion" : "book";
  const statement = marks.length ? ` This is an independent ${kind}. It is not affiliated with, sponsored by, or endorsed by the owners of the names it mentions (${marks.join(", ")}).` : "";
  return `${offering.blurb ?? ""}${statement}`.trim();
}

/** The description with the book's authorship said in it, for retailers whose disclosure lives in the description. */
function disclosedDescription(offering, disclosure) {
  return `${retailDescription(offering)}\n\n${offering.book?.authorship ?? disclosure.text}`;
}

/**
 * What a retailer is told about AI in the making of one book, from its
 * edition record: the text was drafted by AI agents, and proofread by a
 * separate agent only when the edition carries an independent proof; the
 * cover, when there is one, is set in type by code, over an illustration an
 * image model made when the edition names one.
 */
export function aiDisclosureFor(offering) {
  const proofread = Boolean(offering.book?.edition?.proof);
  const generated = offering.book?.generatedIllustrations ?? [];
  const illustration = offering.book?.coverIllustration;
  const cover = !(offering.cover ?? offering.book?.coverFile) ? "No cover image yet."
    : illustration ? `The cover illustration was generated by an AI image model (${illustration.modelName ?? illustration.model}${illustration.provider ? ` on ${illustration.provider}` : ""}) from a prompt written by an AI agent${illustration.references ? `, using ${illustration.references} as reference` : ""}; its title, byline and subtitle were set by code.`
    : offering.book?.coverArt ? "The cover's drawing was written as code (TikZ) by an AI agent and rendered by the typesetter; no image model was used. Its type is set by code from the book's title and design tokens."
    : "None AI-generated: the cover is typeset by code from the book's title and design tokens.";
  const illustrations = generated.length === 0 ? "" : ` Interior illustrations were generated by image model${generated.length === 1 ? "" : "s"}: ${[...new Set(generated.map((asset) => asset.model))].join(", ")}.`;
  return Object.freeze({
    text: `AI-generated: the text was drafted by AI agents working for the 561 Group${proofread ? ", then proofread by a separate AI agent" : ""}.`,
    images: `${cover}${illustrations}`,
    translations: "None.",
  });
}

/**
 * One book's listing on one channel.
 * @param {object} offering a compiled catalog offering with `book` facts
 * @param {string} channel one of RETAIL_CHANNELS
 * @returns {{channel: string, name: string, fields: object, blocks: string[], attention: string[]}}
 */
const seriesLabel = (series) => `${series.name}, number ${series.number}`;
const outermostSeries = (series) => series.within ? outermostSeries(series.within) : series;

export function retailListingFor(offering, channel) {
  if (!RETAIL_CHANNELS.includes(channel)) throw new TypeError(`unknown retail channel ${channel}`);
  const book = offering.book;
  if (!book) throw new TypeError(`${offering.id} is not a book`);
  const marks = book.marks ?? [];
  const price = offering.priceCents;
  const studyGuide = book.profile === "study-guide";
  const blocks = [];
  const attention = [];
  // A rendition without an actual EbookEditionAcceptance is source data,
  // not the edition this publisher can responsibly submit to a retailer.
  // Some historical books retain files even though no edition was accepted.
  if (!book.edition?.record || !book.edition?.acceptedAt)
    blocks.push("No accepted, revision-identified EbookEditionAcceptance is selected. The source must first receive an accepted edition and its exact files.");
  const fields = {
    title: offering.title,
    ...(offering.subtitle ? { subtitle: offering.subtitle } : {}),
    // A retailer shelves a book in one series, the outermost; the series it sits in inside that is its subseries.
    ...(book.series ? { series: seriesLabel(outermostSeries(book.series)) } : {}),
    ...(book.series?.within ? { subseries: seriesLabel(book.series) } : {}),
    author: book.author ?? "561 Group",
    publisher: book.publisher ?? "561 Group",
    language: new Intl.DisplayNames(["en"], { type: "language" }).of(bookLanguageTag(book)),
    description: retailDescription(offering),
    subjects: book.subjects ?? [],
    listPriceUsd: dollars(price),
    files: (book.edition?.files ?? []).map((file) => `${file.format}: ${file.path ?? "(path not recorded)"} (SHA-256 ${file.sha256})`),
    cover: book.coverFile ?? "none",
  };
  const disclosure = aiDisclosureFor(offering);
  // A one-line declaration names every AI-generated part: the text, and the images when an image model made any.
  const imageModel = Boolean(offering.book?.coverIllustration) || (offering.book?.generatedIllustrations ?? []).length > 0;
  const declaration = imageModel ? `${disclosure.text} ${disclosure.images}` : disclosure.text;
  if (!book.coverFile) blocks.push("There is no cover image; every retailer requires one. This edition predates the pipeline's covers, so it needs a new edition.");
  const titleMarks = namesMark(`${offering.title} ${offering.subtitle ?? ""}`, marks);

  if (channel === "kdp") {
    const requestedKeywords = offering.keywords ?? [];
    const eligibleKeywords = requestedKeywords.filter((keyword) => namesMark(keyword, marks).length === 0 && keyword.length <= KDP_KEYWORD_LENGTH);
    const keywords = eligibleKeywords.slice(0, KDP_KEYWORDS);
    Object.assign(fields, {
      keywords,
      royalty: price >= 299 && price <= 1299 ? "70%" : "35%",
      kdpSelect: `No: KDP Select requires digital exclusivity, and the book is sold on shop.561.group${offering.agentOfferUrl ? " and market.561.group" : ""}.`,
      territories: studyGuide ? "United States only (KDP keeps companions to copyrighted works to the US without the rights holder's permission)." : "Worldwide.",
      drm: "No DRM, as on the Group's own storefront.",
      aiDisclosure: disclosure,
      categories: "Choose the Amazon categories closest to the BISAC subjects above.",
    });
    if (titleMarks.length) blocks.push(`The title or subtitle names ${titleMarks.join(", ")}, marks the Group does not own; KDP forbids unauthorized trademarks there, and its title must match the cover. Listing needs a retail edition whose cover and subtitle name the credential generically.`);
    if (price > 1299) attention.push(`At $${dollars(price)} KDP pays 35%; 70% applies from $2.99 to $12.99.`);
    const invalid = requestedKeywords.length - eligibleKeywords.length;
    const overLimit = Math.max(0, eligibleKeywords.length - KDP_KEYWORDS);
    if (invalid > 0) attention.push(`${invalid} keyword(s) naming others' marks or over ${KDP_KEYWORD_LENGTH} characters are left out.`);
    if (overLimit > 0) attention.push(`${overLimit} otherwise eligible keyword(s) are left out because KDP allows ${KDP_KEYWORDS}.`);
    if (/https?:\/\//u.test(fields.description)) blocks.push("KDP descriptions may not carry URLs.");
  } else if (channel === "kdp-paperback") {
    const print = book.print;
    const printEdition = book.printEdition;
    const keywords = (offering.keywords ?? []).filter((keyword) => namesMark(keyword, marks).length === 0 && keyword.length <= KDP_KEYWORD_LENGTH).slice(0, KDP_KEYWORDS);
    Object.assign(fields, {
      keywords,
      categories: "Choose the Amazon categories closest to the BISAC subjects above.",
      aiDisclosure: disclosure,
      territories: studyGuide ? "United States only (KDP keeps companions to copyrighted works to the US without the rights holder's permission)." : "Worldwide.",
      // A paperback uploads its own print files, never the ebook's.
      files: [],
      cover: "none",
    });
    if (!print) blocks.push("The book's ebook.json has no print specification (trim, paper, finish, price, ISBN).");
    else {
      const pages = printEdition?.pages;
      const printing = pages ? kdpPaperbackPrintingCents(pages) : null;
      const rate = print.priceCents >= 999 ? 0.6 : 0.5;
      Object.assign(fields, {
        isbn: print.isbn === "kdp-assigned" ? "Get a free KDP ISBN. Amazon then shows the imprint as Independently published; the copyright page still names the publisher." : print.isbn,
        trim: `${print.trim.width} x ${print.trim.height} in`,
        paper: `${print.ink === "black" ? "Black & white interior" : print.ink}, ${print.paper} paper`,
        bleed: "No bleed.",
        finish: `${print.finish[0].toUpperCase()}${print.finish.slice(1)} cover.`,
        listPriceUsd: dollars(print.priceCents),
        royalty: printing === null ? `${rate * 100}% of list less printing` : `${rate * 100}% of list less $${dollars(printing)} printing: $${dollars(Math.round(print.priceCents * rate - printing))} a copy`,
        expandedDistribution: print.expandedDistribution ? "Yes: bookstores and libraries order it through KDP's Expanded Distribution at 40% of list less printing." : "No.",
        files: printEdition ? [`interior: ${printEdition.interior.path} (SHA-256 ${printEdition.interior.sha256})`, `cover: ${printEdition.cover.path} (SHA-256 ${printEdition.cover.sha256})`] : [],
        cover: printEdition?.cover.path ?? "none",
      });
      if (!printEdition) blocks.push("There is no accepted print edition yet: a print-ready interior PDF at the trim size and a full-wrap cover PDF sized to its page count.");
      else if (printing !== null && print.expandedDistribution && print.priceCents * 0.4 < printing) blocks.push(`At $${dollars(print.priceCents)} Expanded Distribution pays less than the $${dollars(printing)} printing cost; raise the price or turn it off.`);
    }
    if (titleMarks.length) blocks.push(`The title or subtitle names ${titleMarks.join(", ")}, marks the Group does not own; KDP forbids unauthorized trademarks there.`);
    if (/https?:\/\//u.test(fields.description)) blocks.push("KDP descriptions may not carry URLs.");
  } else if (channel === "kobo") {
    // Every house book's text is drafted by AI agents, and Kobo refuses that outright rather than asking for disclosure.
    blocks.push("Kobo rejects books wholly or partly generated by AI (Kobo Writing Life help: Why was my Book Rejected or Blocked?, updated 2026-05-06), and this book's text is AI-generated. It is not listed there, directly or through a distributor that delivers to Kobo.");
  } else if (channel === "google-play-books") {
    // Google asks no AI question; the description says it, as the copyright page does.
    Object.assign(fields, { description: disclosedDescription(offering, disclosure), aiDisclosure: disclosure, identifier: "Google assigns a GGKEY when no ISBN is given.", revenueSplit: "70% of list price on the current terms.", territories: "Worldwide." });
    if (titleMarks.length) attention.push(`The title or subtitle names ${titleMarks.join(", ")}; keep the independence statement in the description.`);
  } else if (channel === "apple-books") {
    const tool = book.textProvenance?.tool;
    Object.assign(fields, {
      description: disclosedDescription(offering, disclosure),
      contributors: [`Author: ${fields.author}`, `AI Generated by: ${tool ?? "(no tool recorded)"}`],
      aiDisclosure: disclosure,
      identifier: "No ISBN is required for an ebook.",
      royalty: "70% of list.",
      territories: "Worldwide.",
    });
    if (!tool) blocks.push("Apple Books rejects an AI-generated book without an \"AI Generated by\" contributor, and ebook.json names no textProvenance.tool.");
    if (titleMarks.length) attention.push(`The title or subtitle names ${titleMarks.join(", ")}; keep the independence statement in the description.`);
  } else if (channel === "barnes-noble-press") {
    const generatedCover = Boolean(book.coverIllustration || book.coverArt);
    Object.assign(fields, {
      keywords: offering.keywords ?? [],
      aiDisclosure: disclosure,
      // B&N asks AI-Created, AI-Assisted or None for each part.
      aiCategories: {
        manuscript: "AI-Created",
        cover: generatedCover ? "AI-Created" : "None",
        images: (book.generatedIllustrations ?? []).length ? "AI-Created" : "None",
        translations: "None",
      },
      royalty: "70% of list.",
      territories: "United States (B&N Press sells on BN.com and NOOK).",
      drm: "No DRM.",
    });
    if (titleMarks.length) attention.push(`The title or subtitle names ${titleMarks.join(", ")}; keep the independence statement in the description.`);
  } else if (channel === "leanpub") {
    Object.assign(fields, {
      minimumPriceUsd: dollars(Math.max(price, 799)),
      suggestedPriceUsd: dollars(price),
      royalty: price >= 799 ? "80%" : "80% less $0.50",
      aiUsage: `Enter on the book's AI Usage page: ${declaration}`,
    });
    if (studyGuide) attention.push("Leanpub's readers are technical; the study companions fit Amazon's and the retailers' certificate-seekers better.");
  }
  return Object.freeze({ channel, name: CHANNEL_NAMES[channel], fields, blocks, attention });
}

/** Every book offering in a catalog, listed on every channel. */
export function retailListings(catalog, channels = RETAIL_CHANNELS) {
  return catalog.offerings.filter((offering) => offering.book).map((offering) => ({
    id: offering.id,
    title: offering.title,
    listings: channels.map((channel) => retailListingFor(offering, channel)),
  }));
}
