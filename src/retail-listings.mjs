/**
 * A catalog book as a listing on an ebook retailer: the fields each
 * retailer's setup form asks for, derived from the book's own metadata and
 * its offer, and what blocks or needs attention before it can be listed
 * there. It is the retail counterpart of stripeOfferingFor: the catalog is
 * the one source, and each channel's listing is a projection of it.
 *
 * Channel rules are the retailers' own, as measured on 2026-09-27 (see
 * 561-group-services-section/content/text/documents/articles/notes/2026/09/27/2026-09-27-note-on-where-to-sell-the-books.md):
 * KDP pays 70% from $2.99 to $12.99 and 35% outside it, forbids
 * unauthorized trademarks in the title, subtitle and keywords, allows seven
 * keywords, and keeps study guides to copyrighted works to the US; Kobo
 * asks for AI-generated material in its contributor metadata; Google Play
 * Books pays 70% of list with no price band; Leanpub pays 80% at $7.99 and up.
 *
 * Measured again on 2026-09-29, from the retailers' own pages: Kobo's help
 * center (updated 2026-05-06) rejects books wholly or partly generated by AI,
 * so it takes no house book; Apple Books requires an "AI Generated by"
 * contributor and a description that says the book is AI-generated
 * (formatting guidelines 1.13, 2.9, 4.8); B&N Press asks whether the
 * manuscript, cover, images and translations are AI-Created or AI-Assisted,
 * and pays a flat 70% on ebooks from $0.99; a KDP paperback in black ink costs
 * $2.30 to print under 110 pages and $1.00 plus $0.012 a page from 110, and
 * pays 60% of list less printing from $9.99 and 50% below.
 */

