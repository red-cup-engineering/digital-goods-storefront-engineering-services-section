#!/usr/bin/env node
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { retailListings } from "../src/retail-listings.mjs";

const LABELS = Object.freeze({
  title: "Title", subtitle: "Subtitle", series: "Series", subseries: "Subseries", author: "Author", publisher: "Publisher", language: "Language",
  description: "Description", subjects: "BISAC subjects", listPriceUsd: "List price (USD)", files: "Files to upload", cover: "Cover image",
  keywords: "Keywords", royalty: "Royalty", kdpSelect: "KDP Select", territories: "Territories", drm: "DRM",
  categories: "Categories", aiDisclosure: "AI disclosure", aiCategories: "AI categories", koboPlus: "Kobo Plus", identifier: "Identifier",
  revenueSplit: "Revenue split", minimumPriceUsd: "Minimum price (USD)", suggestedPriceUsd: "Suggested price (USD)", aiUsage: "AI usage",
  contributors: "Contributors", isbn: "ISBN", trim: "Trim size", paper: "Interior and paper", bleed: "Bleed", finish: "Cover finish",
  expandedDistribution: "Expanded Distribution",
});

function value(field) {
  if (Array.isArray(field)) return field.length ? field.map((item) => `\`${item}\``).join(", ") : "none";
  if (field && typeof field === "object") return Object.entries(field).map(([key, text]) => `${key}: ${text}`).join(" ");
  return String(field);
}

/** Render the listings as a guide a person fills each retailer's form from. */
export function renderRetailListings(listings, { source }) {
  const lines = [
    "# Book retail listings",
    "",
    `Generated by \`digital-goods-storefront-services-section/scripts/derive-retail-listings.mjs\` from ${source}. Do not edit; change a book's \`ebook.json\` or the shop's catalog and regenerate.`,
    "",
    "Each book's section gives what to enter in each retailer's form. **Blocks** must be resolved before the book can be listed there; **attention** items are decisions or checks. File paths are relative to `lib/emsenn/services/561-group/services/`.",
    "",
  ];
  for (const book of listings) {
    lines.push(`## ${book.title}`, "");
    for (const listing of book.listings) {
      lines.push(`### ${listing.name}`, "");
      for (const block of listing.blocks) lines.push(`- **Blocks:** ${block}`);
      for (const item of listing.attention) lines.push(`- **Attention:** ${item}`);
      if (listing.blocks.length || listing.attention.length) lines.push("");
      lines.push("| Field | Enter |", "|---|---|");
      for (const [key, field] of Object.entries(listing.fields)) lines.push(`| ${LABELS[key] ?? key} | ${value(field).replace(/\|/gu, "\\|").replace(/\n/gu, " ")} |`);
      lines.push("");
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/**
 * Derive every book's retail listings from a compiled catalog module and write them as a record and a guide.
 * @param {string} catalogModule path to a module whose default export is a compiled catalog
 * @param {string} recordPath the JSON record to write
 * @param {string} guidePath the Markdown guide to write
 */
export async function deriveRetailListings(catalogModule, recordPath, guidePath) {
  const catalog = (await import(pathToFileURL(resolve(catalogModule)).href)).default;
  const listings = retailListings(catalog);
  // Recorded relative to the services root, like every other path in the listings, whatever the caller's working directory.
  const source = resolve(catalogModule).replace(/^.*?\/lib\/emsenn\/services\/561-group\/services\//u, "");
  writeFileSync(recordPath, `${JSON.stringify({ type: "BookRetailListings", version: 1, source, books: listings }, null, 2)}\n`);
  writeFileSync(guidePath, renderRetailListings(listings, { source: `\`${source}\`` }));
  return listings;
}

if (import.meta.main) {
  const [catalogModule, recordPath, guidePath] = process.argv.slice(2);
  if (!catalogModule || !recordPath || !guidePath) throw new Error("usage: derive-retail-listings.mjs <compiled-catalog.mjs> <record.json> <guide.md>");
  const listings = await deriveRetailListings(catalogModule, recordPath, guidePath);
  const counts = listings.flatMap((book) => book.listings).reduce((sum, listing) => ({ blocks: sum.blocks + listing.blocks.length, attention: sum.attention + listing.attention.length }), { blocks: 0, attention: 0 });
  console.log(JSON.stringify({ books: listings.length, ...counts }));
}
