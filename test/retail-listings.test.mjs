import assert from "node:assert/strict";
import test from "node:test";

import { aiDisclosureFor, AUDIOBOOK_RETAIL_CHANNELS, RETAIL_CHANNELS, retailDescription, retailListingFor, retailListings } from "../src/retail-listings.mjs";

const edition = { digest: "ni:///sha-256;x", proof: { errors: 1, corrections: 2, notes: 3 }, files: [{ format: "EPUB", bytes: 10, sha256: "a".repeat(64), path: "section/dist/book.epub" }] };
const companion = {
  id: "companion", title: "Analysis, Course by Course", subtitle: "An Independent Study Companion to the Google Data Analytics Certificate",
  priceCents: 900, currency: "usd", cover: "/covers/companion.png", blurb: "A study companion.", keywords: ["data analytics", "Google certificate", "SQL"],
  book: { profile: "study-guide", marks: ["Google", "Coursera"], subjects: ["COM021030"], coverFile: "section/dist/companion-cover.png", edition },
};
const handbook = {
  id: "handbook", title: "A Handbook", priceCents: 2900, currency: "usd", blurb: "A field guide.", keywords: ["agents"],
  book: { marks: [], subjects: ["COM004000"], edition: { digest: "release x", proof: null, files: [] } },
};

test("KDP refuses a title naming another's mark, keeps companions to the US, drops marked keywords, and states the royalty", () => {
  const kdp = retailListingFor(companion, "kdp");
  assert.equal(kdp.blocks.length, 1);
  assert.match(kdp.blocks[0], /names Google/);
  assert.match(kdp.fields.territories, /United States only/);
  assert.deepEqual(kdp.fields.keywords, ["data analytics", "SQL"]);
  assert.equal(kdp.fields.royalty, "70%");
  assert.match(kdp.fields.kdpSelect, /^No/);
  const other = retailListingFor(companion, "kobo");
  assert.equal(other.blocks.length, 0);
  assert.match(other.attention[0], /independence statement/);
});

test("the description carries an independence statement exactly when a book names others' marks", () => {
  assert.match(retailDescription(companion), /not affiliated with, sponsored by, or endorsed by the owners of the names it mentions \(Google, Coursera\)/);
  assert.equal(retailDescription(handbook), "A field guide.");
});

test("the AI disclosure says what each edition's record shows, and a book without a cover is blocked everywhere", () => {
  assert.match(aiDisclosureFor(companion).text, /proofread by a separate AI agent/);
  assert.doesNotMatch(aiDisclosureFor(handbook).text, /proofread/);
  for (const channel of RETAIL_CHANNELS) assert.ok(retailListingFor(handbook, channel).blocks.some((block) => /no cover/u.test(block)), channel);
  assert.match(retailListingFor(handbook, "kdp").attention.join(" "), /35%/);
  assert.equal(retailListingFor(handbook, "leanpub").fields.royalty, "80%");
});

test("every book in a catalog is listed on every channel; merch is not a book", () => {
  const books = retailListings({ offerings: [companion, handbook, { id: "merch", title: "Merch", status: "coming-soon" }] });
  assert.deepEqual(books.map((book) => book.id), ["companion", "handbook"]);
  assert.equal(books[0].listings.length, RETAIL_CHANNELS.length);
});

test("KDP distinguishes invalid keywords from the seven-keyword limit", () => {
  const listing = retailListingFor({ ...companion, title: "Plain", subtitle: undefined, keywords: ["one", "two", "three", "four", "five", "six", "seven", "eight", "Google"] }, "kdp");
  assert.deepEqual(listing.fields.keywords, ["one", "two", "three", "four", "five", "six", "seven"]);
  assert.match(listing.attention.join(" "), /1 keyword.*marks/u);
  assert.match(listing.attention.join(" "), /1 otherwise eligible.*allows 7/u);
});

test("a cover whose drawing an agent wrote as code is disclosed as such, and a book off the agent market is not said to be on it", () => {
  const disclosure = aiDisclosureFor({ cover: "/covers/x.png", book: { coverArt: true } });
  assert.match(disclosure.images, /written as code \(TikZ\) by an AI agent/u);
  assert.match(disclosure.images, /no image model/u);
  assert.match(aiDisclosureFor({ cover: "/covers/x.png", book: {} }).images, /^None AI-generated/u);
  assert.equal(aiDisclosureFor({ cover: "/covers/x.jpg", book: { coverIllustration: { model: "@cf/black-forest-labs/flux-2-dev", modelName: "FLUX.2 [dev]", provider: "Cloudflare Workers AI", references: "public-domain photographs of the Aerial Lift Bridge" } } }).images,
    "The cover illustration was generated by an AI image model (FLUX.2 [dev] on Cloudflare Workers AI) from a prompt written by an AI agent, using public-domain photographs of the Aerial Lift Bridge as reference; its title, byline and subtitle were set by code.");
  assert.match(aiDisclosureFor({ cover: "/covers/x.png", book: { generatedIllustrations: [{ model: "flux-1-schnell" }] } }).images, /Interior illustrations were generated by image model: flux-1-schnell/u);
});

test("audiobook channel policy is structured first-party data, including restrictions and refusal", () => {
  assert.deepEqual(AUDIOBOOK_RETAIL_CHANNELS.filter(({ disposition }) => disposition === "accepts").map(({ id }) => id), ["google-play-books", "kobo", "spotify"]);
  assert.equal(AUDIOBOOK_RETAIL_CHANNELS.find(({ id }) => id === "inaudio").packaging.startsWith("Unmodified LPF"), true);
  assert.equal(AUDIOBOOK_RETAIL_CHANNELS.find(({ id }) => id === "apple-books").disposition, "program-only");
  assert.equal(AUDIOBOOK_RETAIL_CHANNELS.find(({ id }) => id === "acx").disposition, "refuses-house-synthesis");
  for (const channel of AUDIOBOOK_RETAIL_CHANNELS) assert.match(channel.source, /^https:\/\//u);
});
